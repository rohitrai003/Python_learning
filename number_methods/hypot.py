# Hypotenuse function
# Hypotenuse function returns the length of the hypotenuse of a right-angled triangle given the lengths of the other two sides.
import math
side_a = 3
side_b = 4
hypotenuse_length = math.hypot(side_a, side_b)
print("The length of the hypotenuse of a right-angled triangle with sides", side_a, "and", side_b, "is", hypotenuse_length)